/**
 * Pre-bundles `src/bootstrap.ts` (with `@copylocker/guard` inlined) into a
 * self-contained IIFE string module at `src/generated/bootstrap-source.ts`.
 * The plugin prepends that source to entry chunks at `generateBundle` time —
 * after the host bundler ran, so no module resolution is needed at that
 * point. Runs before tsc/vitest (npm pre-hooks).
 */

import { mkdir, writeFile, access } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')

async function ensureGuardBuilt() {
  const guardDist = join(root, 'node_modules/@copylocker/guard/dist/index.js')
  try {
    await access(guardDist)
  } catch {
    console.error(
      'CopyLocker unplugin: @copylocker/guard is not built — run `npm install && npm run build` in packages/guard first',
    )
    process.exit(1)
  }
}

await ensureGuardBuilt()

const esbuild = await import('esbuild')
const result = await esbuild.build({
  entryPoints: [join(root, 'src/bootstrap.ts')],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  legalComments: 'none',
  logLevel: 'silent',
})
const source = result.outputFiles[0].text
if (/[^\x00-\x7f]/.test(source)) {
  throw new Error('bootstrap bundle is not pure ASCII — check esbuild comment stripping')
}

const outFile = join(root, 'src/generated/bootstrap-source.ts')
await mkdir(dirname(outFile), { recursive: true })
await writeFile(
  outFile,
  [
    '/** GENERATED by scripts/build-bootstrap.mjs — do not edit. */',
    `export const BOOTSTRAP_SOURCE = ${JSON.stringify(source)}`,
    '',
  ].join('\n'),
)
console.log(`bootstrap bundle: ${source.length} bytes -> src/generated/bootstrap-source.ts`)
